// Regenerates the TUNABLE block at the end of src/config.ts: every numeric `export let` becomes moddable.
// Run after adding a number to config.ts: `bun tools/gen-tunables.ts` (a test fails when the block is stale).
const path = new URL("../src/config.ts", import.meta.url).pathname;
let src = await Bun.file(path).text();
// numeric constants become live `let` bindings so a mod can change them before the game starts
src = src.replace(/^export const ([A-Z][A-Z0-9_]*\s*=\s*-?[\d._]+(?:\s*\/\s*[\d._]+)?\s*(?:,\s*[A-Z][A-Z0-9_]*\s*=\s*-?[\d._]+\s*)*;)/gm, "export let $1");
const names: string[] = [];
for (const m of src.matchAll(/^export let (.+);/gm))
  for (const part of m[1].split(/,(?![^(]*\))/)) { const n = part.trim().match(/^([A-Z][A-Z0-9_]*)\s*=/); if (n) names.push(n[1]); }
const START = "// ---- TUNABLE (generated by tools/gen-tunables.ts; do not edit by hand) ----";
const END = "// ---- end TUNABLE ----";
const block = `${START}\n/** Every plain number above, by name, for mods: [read, write]. */\nexport const TUNABLE: Record<string, [() => number, (v: number) => void]> = {\n` +
  names.map(n => `  ${n}: [() => ${n}, v => { ${n} = v; }],`).join("\n") + `\n};\n${END}\n`;
const i = src.indexOf(START);
src = i >= 0 ? src.slice(0, i) + block + src.slice(src.indexOf(END) + END.length + 1) : src + "\n" + block;
await Bun.write(path, src);
console.log(`${names.length} tunables`);
